/*
 * LeetCode 217. Contains Duplicate（包含重複元素）— 雜湊集合法
 * 難度：Easy
 * 時間複雜度：O(n)    — 每個元素最多查詢與插入各一次，均攤 O(1)
 * 空間複雜度：O(n)    — 雜湊表最多存放 n 個元素
 *
 * ======================================================================
 * 演算法：雜湊集合 (Hash Set)
 * ======================================================================
 *
 * 核心思想：
 *   使用雜湊表模擬集合 (set) 的功能。
 *   遍歷陣列時，對每個元素先查詢是否已存在於集合中：
 *     - 若已存在 → 找到重複，回傳 true
 *     - 若不存在 → 將該元素插入集合，繼續下一個
 *   遍歷結束仍未找到重複 → 回傳 false
 *
 * 雜湊表實作細節（開放定址法 / Open Addressing + Linear Probing）：
 *   - 桶數量 capacity 取 numsSize * 2，降低碰撞機率
 *   - 每個桶有三種狀態：EMPTY（空）、OCCUPIED（已佔用）
 *   - 雜湊函式：將 key 映射到 [0, capacity) 的非負索引
 *     hash(key) = ((key % capacity) + capacity) % capacity
 *     先取餘再加 capacity 再取餘，確保負數也能正確映射
 *   - 碰撞處理：線性探測，逐一往後尋找空桶
 *
 * ======================================================================
 * 範例演示：nums = [1, 2, 3, 1]，capacity = 8
 * ======================================================================
 *
 *   初始雜湊表（8 個桶，全部 EMPTY）：
 *   ┌───────┬───────┬───────┬───────┬───────┬───────┬───────┬───────┐
 *   │ EMPTY │ EMPTY │ EMPTY │ EMPTY │ EMPTY │ EMPTY │ EMPTY │ EMPTY │
 *   └───────┴───────┴───────┴───────┴───────┴───────┴───────┴───────┘
 *     [0]     [1]     [2]     [3]     [4]     [5]     [6]     [7]
 *
 *   Step 1: 處理 nums[0] = 1
 *     hash(1) = 1 % 8 = 1 → 桶[1] 是 EMPTY → 不重複，插入
 *   ┌───────┬───────┬───────┬───────┬───────┬───────┬───────┬───────┐
 *   │ EMPTY │   1   │ EMPTY │ EMPTY │ EMPTY │ EMPTY │ EMPTY │ EMPTY │
 *   └───────┴───────┴───────┴───────┴───────┴───────┴───────┴───────┘
 *                ▲ 插入
 *
 *   Step 2: 處理 nums[1] = 2
 *     hash(2) = 2 % 8 = 2 → 桶[2] 是 EMPTY → 不重複，插入
 *   ┌───────┬───────┬───────┬───────┬───────┬───────┬───────┬───────┐
 *   │ EMPTY │   1   │   2   │ EMPTY │ EMPTY │ EMPTY │ EMPTY │ EMPTY │
 *   └───────┴───────┴───────┴───────┴───────┴───────┴───────┴───────┘
 *                         ▲ 插入
 *
 *   Step 3: 處理 nums[2] = 3
 *     hash(3) = 3 % 8 = 3 → 桶[3] 是 EMPTY → 不重複，插入
 *   ┌───────┬───────┬───────┬───────┬───────┬───────┬───────┬───────┐
 *   │ EMPTY │   1   │   2   │   3   │ EMPTY │ EMPTY │ EMPTY │ EMPTY │
 *   └───────┴───────┴───────┴───────┴───────┴───────┴───────┴───────┘
 *                                ▲ 插入
 *
 *   Step 4: 處理 nums[3] = 1
 *     hash(1) = 1 % 8 = 1 → 桶[1] 已佔用且值 == 1 → 找到重複！
 *   ┌───────┬───────┬───────┬───────┬───────┬───────┬───────┬───────┐
 *   │ EMPTY │  [1]  │   2   │   3   │ EMPTY │ EMPTY │ EMPTY │ EMPTY │
 *   └───────┴───────┴───────┴───────┴───────┴───────┴───────┴───────┘
 *                ▲ 命中！回傳 true ✓
 *
 * ======================================================================
 * 範例演示：nums = [1, 2, 3, 4]，capacity = 8
 * ======================================================================
 *
 *   依序插入 1, 2, 3, 4，每次查詢皆未命中：
 *   ┌───────┬───────┬───────┬───────┬───────┬───────┬───────┬───────┐
 *   │ EMPTY │   1   │   2   │   3   │   4   │ EMPTY │ EMPTY │ EMPTY │
 *   └───────┴───────┴───────┴───────┴───────┴───────┴───────┴───────┘
 *   遍歷結束 → 回傳 false ✓
 *
 * ======================================================================
 * 碰撞演示：假設 capacity = 8，插入 1 和 9
 * ======================================================================
 *
 *   hash(1) = 1，hash(9) = 9 % 8 = 1 → 碰撞！
 *
 *   插入 1 後：
 *   ┌───────┬───────┬───────┬ ...
 *   │ EMPTY │   1   │ EMPTY │
 *   └───────┴───────┴───────┘
 *              [1]
 *
 *   插入 9：桶[1] 已佔用且值 ≠ 9 → 線性探測 → 桶[2] EMPTY → 插入
 *   ┌───────┬───────┬───────┬ ...
 *   │ EMPTY │   1   │   9   │
 *   └───────┴───────┴───────┘
 *              [1]     [2]
 *                       ▲ 探測後插入
 */

#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

/* 桶的狀態標記 */
#define EMPTY    0   /* 此桶尚未使用 */
#define OCCUPIED 1   /* 此桶已存放元素 */

/* 雜湊表的桶結構 */
typedef struct {
    int key;         /* 儲存的整數值 */
    int state;       /* 桶的狀態：EMPTY 或 OCCUPIED */
} Bucket;

/* 雜湊函式：將整數 key 映射到 [0, capacity) 的非負索引 */
/* 先取餘再加 capacity 再取餘，處理負數的情況 */
static inline int hashFunc(int key, int capacity) {
    return ((key % capacity) + capacity) % capacity;
}

bool containsDuplicate(int* nums, int numsSize) {
    /* 邊界條件：空陣列或僅一個元素，不可能有重複 */
    if (numsSize <= 1) {
        return false;
    }

    /* 雜湊表容量設為 numsSize 的兩倍，降低碰撞機率（負載因子 ≤ 0.5） */
    int capacity = numsSize * 2;

    /* 配置雜湊表記憶體並初始化為全零（所有桶狀態為 EMPTY = 0） */
    Bucket* table = (Bucket*)calloc(capacity, sizeof(Bucket));
    if (!table) {
        return false;  /* 記憶體配置失敗，安全退出 */
    }

    /* 遍歷陣列中的每個元素 */
    for (int i = 0; i < numsSize; i++) {
        int key = nums[i];                    /* 當前要檢查的值 */
        int idx = hashFunc(key, capacity);    /* 計算雜湊索引 */

        /* 線性探測：尋找 key 是否已存在，或找到空桶插入 */
        while (table[idx].state != EMPTY) {
            /* 桶已佔用，檢查是否為相同的值 */
            if (table[idx].key == key) {
                /* @@@找到重複元素！釋放記憶體後回傳 true */
                free(table);
                return true;
            }
            /* 不是相同的值 → 碰撞，往下一個桶探測（環繞） */
            idx = (idx + 1) % capacity;
        }

        /* 探測到空桶，表示 key 尚未出現過，插入此桶 */
        table[idx].key = key;        /* 存放鍵值 */
        table[idx].state = OCCUPIED; /* 標記為已佔用 */
    }

    /* 遍歷完所有元素，未發現任何重複 */
    free(table);   /* 釋放雜湊表記憶體 */
    return false;
}
